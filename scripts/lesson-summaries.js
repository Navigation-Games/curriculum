// Teacher-facing lesson summaries, read from the `summary:` line in each
// school lesson's frontmatter (content/lessons/school/<band>/<lesson>.md).
//
// The summary is one sentence or phrase for teachers about what the lesson
// teaches (the `tagline:` is the kid-facing line). It is written once in the
// lesson file and shown wherever lessons are summarized briefly: under the
// lesson page title, in the grade band tables and the Activities & Lesson
// Plans page (through <LessonSummary>), in Unit 4 of the teacher course
// ({{lessons <band>}}), and in the advisor's site map.

const fs = require('fs');
const path = require('path');
const yaml = require(require.resolve('js-yaml', { paths: [path.join(__dirname, '..', 'site')] }));

const REPO_ROOT = path.join(__dirname, '..');
const LESSONS_DIR = path.join(REPO_ROOT, 'content', 'lessons', 'school');

// Activity card tags that name what the lesson is about (not warm-ups or extensions)
const MAIN_ACTIVITY_TAGS = new Set(['core', 'readiness', 'variation']);

// { "grade-3-5/lesson-1": {title, number, name, summary, url, activities} }
function collectLessonSummaries() {
  const lessons = {};
  if (!fs.existsSync(LESSONS_DIR)) return lessons;
  for (const band of fs.readdirSync(LESSONS_DIR)) {
    const dir = path.join(LESSONS_DIR, band);
    if (!fs.statSync(dir).isDirectory()) continue;
    for (const file of fs.readdirSync(dir).filter(f => f.endsWith('.md'))) {
      const slug = path.basename(file, '.md');
      const raw = fs.readFileSync(path.join(dir, file), 'utf8').replace(/\r\n/g, '\n');
      const title = (raw.match(/^# (.+)$/m) || [])[1]?.trim() || slug;
      const fmText = (raw.match(/^---\n([\s\S]*?)\n---/m) || [])[1];
      let fm = {};
      try {
        fm = (fmText && yaml.load(fmText)) || {};
      } catch {
        // Bad YAML is reported by the main build
      }
      const numbered = title.match(/^([0-9]+|[A-Z]) - (.+)$/);
      const activities = [];
      for (const a of fm.activities || []) {
        if (a?.title && MAIN_ACTIVITY_TAGS.has(a.tag) && !activities.includes(a.title)) activities.push(a.title);
      }
      lessons[`${band}/${slug}`] = {
        title,
        number: numbered ? numbered[1] : '',
        name: numbered ? numbered[2] : title,
        summary: fm.summary ? String(fm.summary) : '',
        url: `/lessons/school/${band}/${slug}/`,
        activities,
      };
    }
  }
  return lessons;
}

// The site/src data module that <LessonSummary> reads (gitignored, rebuilt on every build)
function writeLessonSummaries(lessons) {
  const outDir = path.join(REPO_ROOT, 'site', 'src', 'components', 'LessonSummary');
  if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });
  const outPath = path.join(outDir, 'lessonSummaries.ts');
  const data = {};
  for (const [key, l] of Object.entries(lessons)) data[key] = { title: l.title, summary: l.summary, url: l.url };
  fs.writeFileSync(
    outPath,
    '// AUTO-GENERATED by scripts/build-content.js from the `summary:` lines in content/lessons/school/ — do not edit directly\n' +
      '\n' +
      'export interface LessonSummaryData {\n  title: string;\n  summary: string;\n  url: string;\n}\n' +
      '\n' +
      `const lessonSummaries: Record<string, LessonSummaryData> = ${JSON.stringify(data, null, 2)};\n` +
      '\n' +
      'export default lessonSummaries;\n',
    'utf8',
  );
  return path.relative(REPO_ROOT, outPath);
}

// Markdown list of a band's numbered lessons, for {{lessons <band>}} in course pages:
// "1. **[Know Your Space](/lessons/...).** Summary. Boundary Run, Gathering."
// With shuffled, the list is lettered A, B, C... in a fixed scrambled order,
// with names and summaries only (no links or numbers, which would give the
// order away), for Unit 4's "put the lessons in order" exercise. The order is
// the same on every build, so the page and the tutor always agree.
function lessonListMarkdown(band, lessons = collectLessonSummaries(), { shuffled = false } = {}) {
  const inOrder = Object.entries(lessons)
    .filter(([key, l]) => key.startsWith(`${band}/`) && /^[0-9]+$/.test(l.number))
    .sort(([, a], [, b]) => Number(a.number) - Number(b.number));
  if (shuffled) {
    const n = inOrder.length;
    return inOrder
      .map(([, l], i) => ({ l, key: ((i + 1) * 5) % (n + 1) }))
      .sort((a, b) => a.key - b.key || a.l.name.localeCompare(b.l.name))
      .map(({ l }, i) => `- **${String.fromCharCode(65 + i)}. ${l.name}.**${l.summary ? ` ${l.summary}` : ''}`)
      .join('\n');
  }
  return inOrder
    .map(([, l]) => {
      const summary = l.summary ? ` ${l.summary}` : '';
      const acts = l.activities.length ? ` ${l.activities.join(', ')}.` : '';
      return `${l.number}. **[${l.name}](${l.url}).**${summary}${acts}`;
    })
    .join('\n');
}

module.exports = { collectLessonSummaries, writeLessonSummaries, lessonListMarkdown };
